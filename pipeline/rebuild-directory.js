#!/usr/bin/env node
/* Regenerate directory.js from the account-directory-taxonomy sheet CSV.
   Reads the curated tab (Handle | Display Name | Type | Discipline | Category),
   extracts the handle from each IG URL, and rewrites directory.js in place.

   The Google-Sheets host isn't reachable from the workspace shell, so this script
   does NOT fetch — the CSV is supplied by the caller (the weekly agent uses
   web_fetch, then pipes it here):

     node rebuild-directory.js path/to/sheet.csv
     cat sheet.csv | node rebuild-directory.js

   Deterministic, no network, no token. */

const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, 'directory.js');

// Minimal RFC-4180 CSV parser (handles quoted fields, commas, newlines).
function parseCSV(text) {
  const rows = []; let row = [], field = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"') { if (text[i + 1] === '"') { field += '"'; i++; } else q = false; }
      else field += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(field); field = ''; }
    else if (c === '\n') { row.push(field); rows.push(row); row = []; field = ''; }
    else if (c === '\r') { /* skip */ }
    else field += c;
  }
  if (field.length || row.length) { row.push(field); rows.push(row); }
  return rows;
}

const handleFromUrl = u => String(u || '').trim()
  .replace(/^https?:\/\/(www\.)?instagram\.com\//i, '')
  .replace(/[/?].*$/, '').replace(/^@/, '').trim();

(async () => {
  const arg = process.argv[2];
  const csv = arg ? fs.readFileSync(arg, 'utf8') : fs.readFileSync(0, 'utf8');
  if (!csv.trim()) throw new Error('no CSV supplied (pass a file path or pipe via stdin)');
  const rows = parseCSV(csv);
  if (!rows.length) throw new Error('empty sheet');

  // Drop header row; keep rows with a handle + type.
  const body = rows.slice(1);
  const seen = new Set();
  const recs = [];
  let skipped = 0;
  for (const r of body) {
    const handle = handleFromUrl(r[0]);
    const name = (r[1] || '').trim();
    const type = (r[2] || '').trim();
    const disc = (r[3] || '').trim();
    const cat = (r[4] || '').trim();
    if (!handle || !type) { skipped++; continue; }
    const key = handle.toLowerCase();
    if (seen.has(key)) { skipped++; continue; }
    seen.add(key);
    recs.push([handle, name, type, disc, cat]);
  }

  // Diff against the existing directory (if present) so the caller can report changes.
  let added = recs.map(r => r[0]), removed = [];
  try {
    const prev = require(OUT);
    const prevSet = new Set((prev.list || []).map(e => String(e[0]).toLowerCase()));
    const newSet = new Set(recs.map(e => e[0].toLowerCase()));
    added = recs.filter(e => !prevSet.has(e[0].toLowerCase())).map(e => `${e[0]} (${e[2]}·${e[3]}·${e[4]})`);
    removed = [...prevSet].filter(h => !newSet.has(h));
  } catch (e) { /* first run — no prior file */ }

  const lines = recs.map(e => JSON.stringify(e)).join(', ');
  const out = `/* IG-Analysis directory — baked from the account-directory-taxonomy sheet.
   ${recs.length} accounts. Known handles skip the classifier and use these values; also powers autocomplete.
   Auto-generated by rebuild-directory.js — do not hand-edit. */
(function (root) {
  // [handle, displayName, type, discipline, category]
  const D = [${lines}];
  const benchmarkFor = t => (t === 'Athlete' || t === 'Creator') ? 'creator' : 'brand';
  const byHandle = {};
  D.forEach(e => { byHandle[e[0].toLowerCase()] = { handle: e[0], name: e[1], type: e[2], discipline: e[3], category: e[4], benchmarkType: benchmarkFor(e[2]) }; });
  const API = { list: D, lookup: h => byHandle[(h||'').replace(/^@/,'').toLowerCase()] || null, count: D.length };
  if (typeof module !== 'undefined' && module.exports) module.exports = API;
  root.IGDir = API;
})(typeof window !== 'undefined' ? window : globalThis);
`;
  fs.writeFileSync(OUT, out);
  console.log(`directory.js rebuilt — ${recs.length} accounts (${skipped} rows skipped).`);
  console.log(`ADDED (${added.length}): ${added.length ? added.join(', ') : 'none'}`);
  console.log(`REMOVED (${removed.length}): ${removed.length ? removed.join(', ') : 'none'}`);
})().catch(e => { console.error('FAILED:', e.message); process.exit(1); });
